#!/usr/bin/env bash
# factory.sh: the riehub software factory driver.
#
#   factory/factory.sh status              progress per version, blocked tasks, what is next
#   factory/factory.sh next                print the next task card to work on
#   factory/factory.sh show T-0101         print one task card
#   factory/factory.sh start T-0101        create the task branch (or resume a blocked one)
#   factory/factory.sh gate                run `make gate` on the committed tree, record the result
#   factory/factory.sh finish T-0101       verify, record proof, merge to main, delete the branch
#   factory/factory.sh block T-0101 "why"  park a task that cannot be finished, go back to main
#   factory/factory.sh release 0.1.0       tag a version once all of its tasks are done
#   factory/factory.sh approve T-1099      HUMAN ONLY: open a task marked `Gate: human`
#   factory/factory.sh progress            regenerate docs/PROGRESS.md
#
# Rules it enforces are described in factory/README.md and ADR 0003.
# Exit codes: 0 ok, 1 error, 3 nothing runnable (blocked or waiting for a human).

set -euo pipefail

ROOT="$(git -C "$(dirname "${BASH_SOURCE[0]}")" rev-parse --show-toplevel)"
cd "$ROOT"

MAIN="main"
TASKS_DIR="factory/tasks"
STATE="factory/state.tsv"            # committed: id <TAB> done <TAB> date <TAB> proof
LOCAL_DIR="$(git rev-parse --git-dir)/factory"
LOCAL="$LOCAL_DIR/local.tsv"         # per clone: id <TAB> doing|blocked|approved <TAB> note
STAMP="$LOCAL_DIR/gate-stamp"        # tree hash of the last green gate
GATE_LOG="$LOCAL_DIR/gate.log"
TAB="$(printf '\t')"

mkdir -p "$LOCAL_DIR"
touch "$LOCAL"

die() { echo "factory: $*" >&2; exit 1; }

# ---- the task index, read from the cards: id, version, depends, review, gate, type, title
index() {
  # shellcheck disable=SC2046
  awk '
    function flush() {
      if (id != "") printf "%s\t%s\t%s\t%s\t%s\t%s\t%s\n", id, ver, dep, rev, gate, type, title
    }
    /^## T-[0-9][0-9][0-9][0-9] / {
      flush(); id = $2; title = $0; sub(/^## T-[0-9]+ /, "", title)
      ver = "-"; dep = "-"; rev = "standard"; gate = "auto"; type = "feat"; next
    }
    id != "" && /^- Version: / { ver = $3 }
    id != "" && /^- Depends: / {
      d = $0; sub(/^- Depends: */, "", d); gsub(/ /, "", d)
      dep = (d == "" || d == "none") ? "-" : d
    }
    id != "" && /^- Review: /  { rev = $3 }
    id != "" && /^- Gate: /    { gate = $3 }
    id != "" && /^- Type: /    { type = $3 }
    END { flush() }
  ' $(find "$TASKS_DIR" -name 'M*.md' | sort)
}

field() {  # field <id> <column-number>
  index | awk -F'\t' -v id="$1" -v c="$2" '$1 == id { print $c; found = 1 } END { exit !found }' \
    || die "unknown task $1"
}

is_done() { awk -F'\t' -v id="$1" '$1 == id && $2 == "done" { f = 1 } END { exit !f }' "$STATE"; }

local_state() {  # prints doing|blocked|approved or nothing
  awk -F'\t' -v id="$1" '$1 == id { print $2 }' "$LOCAL" | tail -n 1
}

local_note() { awk -F'\t' -v id="$1" '$1 == id { print $3 }' "$LOCAL" | tail -n 1; }

set_local() {  # set_local <id> <state|-> [note]   ("-" removes the entry)
  local tmp="$LOCAL.tmp"
  awk -F'\t' -v id="$1" '$1 != id' "$LOCAL" > "$tmp"
  if [ "$2" != "-" ]; then printf '%s\t%s\t%s\n' "$1" "$2" "${3:-}" >> "$tmp"; fi
  mv "$tmp" "$LOCAL"
}

state_of() {  # done | doing | blocked | todo
  if is_done "$1"; then echo done; return; fi
  case "$(local_state "$1")" in
    doing) echo doing ;;
    blocked) echo blocked ;;
    *) echo todo ;;
  esac
}

deps_done() {  # deps_done <comma-list or ->
  [ "$1" = "-" ] && return 0
  local d
  for d in ${1//,/ }; do is_done "$d" || return 1; done
}

show() {
  local out
  out="$(awk -v id="$1" '
    /^## T-[0-9][0-9][0-9][0-9] / { on = ($2 == id) }
    /^# / { on = 0 }
    on { print }
  ' $(find "$TASKS_DIR" -name 'M*.md' | sort))"
  [ -n "$out" ] || die "unknown task $1"
  printf '%s\n' "$out"
}

current_branch() { git symbolic-ref --quiet --short HEAD 2>/dev/null || echo ""; }
clean_tree() { [ -z "$(git status --porcelain)" ]; }

slug() {
  printf '%s' "$1" | tr '[:upper:]' '[:lower:]' | sed -E 's/[^a-z0-9]+/-/g; s/^-+//; s/-+$//' | cut -c1-40 | sed -E 's/-+$//'
}

branch_of() { printf '%s/%s-%s' "$(field "$1" 6)" "$1" "$(slug "$(field "$1" 7)")"; }

mode() {  # pr | local
  case "${FACTORY_MODE:-auto}" in
    pr|local) echo "${FACTORY_MODE}"; return ;;
  esac
  if command -v gh >/dev/null 2>&1 && gh auth status >/dev/null 2>&1 \
     && git remote get-url origin >/dev/null 2>&1 \
     && timeout 15 git ls-remote --exit-code origin "$MAIN" >/dev/null 2>&1; then
    echo pr
  else
    echo local
  fi
}

# ---- commands

cmd_progress() {
  local out="docs/PROGRESS.md"
  {
    echo "# riehub progress"
    echo
    echo "This page is generated by \`factory/factory.sh\` from the task cards"
    echo "and \`factory/state.tsv\`. Do not edit it by hand. A row is \`done\` only"
    echo "after the gate (\`make gate\`) was green on the merged tree, and the"
    echo "proof column names that tree. The plan behind the rows is the"
    echo "[roadmap](ROADMAP.md)."
    echo
    echo "| Task | Title | Version | State | Proof |"
    echo "|---|---|---|---|---|"
    index | while IFS="$TAB" read -r id ver _dep _rev _gate _type title; do
      if is_done "$id"; then
        proof="$(awk -F'\t' -v id="$id" '$1 == id { print $3 ", " $4 }' "$STATE" | tail -n 1)"
        echo "| $id | $title | $ver | done | $proof |"
      else
        echo "| $id | $title | $ver | todo | |"
      fi
    done
    echo
    echo "## Known gaps / open items"
    echo
    echo "Blocked tasks and their reasons are local to a working clone:"
    echo "\`factory/factory.sh status\` lists them. Anything that outlives a"
    echo "session is filed as a GitHub issue."
  } > "$out"
}

cmd_status() {
  echo "mode: $(mode)   branch: $(current_branch)"
  index | awk -F'\t' -v state="$STATE" '
    BEGIN { while ((getline line < state) > 0) { split(line, a, "\t"); if (a[2] == "done") done[a[1]] = 1 } }
    { total[$2]++; if ($1 in done) ok[$2]++; if (!($2 in seen)) { seen[$2] = 1; order[++n] = $2 } }
    END { for (i = 1; i <= n; i++) printf "  %-7s %d/%d done\n", order[i], ok[order[i]] + 0, total[order[i]] }
  '
  awk -F'\t' '$2 == "doing"   { print "doing:   " $1 }' "$LOCAL"
  awk -F'\t' '$2 == "blocked" { print "blocked: " $1 " - " $3 }' "$LOCAL"
  echo "next:    $(pick || true)"
}

pick() {  # prints the id to work on, or a STOP/DONE line. returns 0 only for a task id
  local doing
  doing="$(awk -F'\t' '$2 == "doing" { print $1; exit }' "$LOCAL")"
  if [ -n "$doing" ]; then echo "$doing"; return 0; fi
  local id ver dep rev gate type title st remaining=0 waiting=""
  while IFS="$TAB" read -r id ver dep rev gate type title; do
    st="$(state_of "$id")"
    [ "$st" = "done" ] && continue
    remaining=$((remaining + 1))
    if [ "$st" = "blocked" ]; then waiting="$waiting $id(blocked)"; continue; fi
    deps_done "$dep" || continue
    if [ "$gate" = "human" ] && [ "$(local_state "$id")" != "approved" ]; then
      waiting="$waiting $id(human-gate)"; continue
    fi
    echo "$id"; return 0
  done < <(index)
  if [ "$remaining" -eq 0 ]; then echo "DONE: every task is done"; return 2; fi
  echo "STOP: nothing runnable, waiting on:${waiting:- unmet dependencies}"; return 3
}

cmd_next() {
  local id rc=0
  id="$(pick)" || rc=$?
  if [ "$rc" -ne 0 ]; then
    echo "$id"
    [ "$rc" -eq 2 ] && exit 0
    exit 3
  fi
  local st; st="$(state_of "$id")"
  echo "TASK $id  state=$st  version=$(field "$id" 2)  review=$(field "$id" 4)  branch=$(branch_of "$id")"
  echo
  show "$id"
  echo
  if [ "$st" = "doing" ]; then
    echo "Resume: git checkout $(branch_of "$id")"
  else
    echo "Begin:  factory/factory.sh start $id"
  fi
}

cmd_start() {
  local id="${1:?usage: start T-NNNN}" st branch
  git rev-parse --verify -q "$MAIN" >/dev/null || die "no commit on $MAIN yet, do the bootstrap in AGENTS.md section 3 first"
  clean_tree || die "working tree is not clean, commit or discard first"
  st="$(state_of "$id")"
  [ "$st" != "done" ] || die "$id is already done"
  deps_done "$(field "$id" 3)" || die "$id depends on tasks that are not done: $(field "$id" 3)"
  if [ "$(field "$id" 5)" = "human" ] && [ "$(local_state "$id")" != "approved" ] && [ "$st" = "todo" ]; then
    die "$id needs the maintainer: it is marked Gate: human"
  fi
  local other
  other="$(awk -F'\t' -v id="$id" '$2 == "doing" && $1 != id { print $1; exit }' "$LOCAL")"
  [ -z "$other" ] || die "$other is still in progress, finish or block it first"
  branch="$(branch_of "$id")"
  if git rev-parse --verify -q "refs/heads/$branch" >/dev/null; then
    git checkout -q "$branch"
  else
    [ "$(current_branch)" = "$MAIN" ] || git checkout -q "$MAIN"
    git checkout -q -b "$branch"
  fi
  set_local "$id" doing
  rm -f "$STAMP"
  echo "on branch $branch, $id is in progress"
}

cmd_gate() {
  clean_tree || die "commit your work first, the gate runs on the committed tree"
  echo "running make gate (full log: $GATE_LOG)"
  if make gate > "$GATE_LOG" 2>&1; then
    git rev-parse 'HEAD^{tree}' > "$STAMP"
    echo "GATE GREEN for tree $(cut -c1-12 "$STAMP")"
  else
    rm -f "$STAMP"
    echo "GATE RED. Last 60 lines:"
    tail -n 60 "$GATE_LOG"
    exit 1
  fi
}

check_attribution() {
  # R1, strict: no AI signature or mark of any kind. Messages first.
  if git log "$MAIN..HEAD" --format='%B' \
     | grep -iE 'co-authored-by:|generated (with|by)|assisted[- ]by|written (with|by) (an? )?(ai|llm|claude|chatgpt|copilot|gemini|codex|cursor)|🤖|noreply@anthropic|noreply@openai' >/dev/null; then
    die "a commit message on this branch carries an AI signature or a co-author trailer, rewrite it (AGENTS.md rule R1)"
  fi
  # Then who the commits claim to be from.
  if git log "$MAIN..HEAD" --format='%an%n%ae%n%cn%n%ce' \
     | grep -iE 'claude|anthropic|openai|chatgpt|copilot|codex|gemini|deepseek|cursor|aider|\[bot\]|(^|[^a-z])(ai|bot|agent)([^a-z]|$)' >/dev/null; then
    die "a commit on this branch has a tool as author or committer, commit under the maintainer's git identity (AGENTS.md rule R1)"
  fi
  # writing style applies to commit messages too (AGENTS.md section 8)
  if git log "$MAIN..HEAD" --format='%B' | grep -E "$(printf '\342\200\224')|;" >/dev/null; then
    die "a commit message on this branch has an em-dash or a semicolon, rewrite it (AGENTS.md section 8)"
  fi
}

cmd_finish() {
  local id="${1:?usage: finish T-NNNN}" branch type title tree m
  branch="$(branch_of "$id")"
  [ "$(current_branch)" = "$branch" ] || die "check out $branch first"
  clean_tree || die "working tree is not clean"
  tree="$(git rev-parse 'HEAD^{tree}')"
  [ -f "$STAMP" ] && [ "$(cat "$STAMP")" = "$tree" ] \
    || die "no green gate for this tree, run: factory/factory.sh gate"
  [ -n "$(git log "$MAIN..HEAD" --oneline)" ] || die "the branch has no commits"
  check_attribution
  type="$(field "$id" 6)"; title="$(field "$id" 7)"
  if [ "$(field "$id" 4)" = "security" ]; then
    [ -f "factory/reviews/$id.md" ] || die "missing factory/reviews/$id.md (Review: security, see factory/SECURITY-CHECKLIST.md)"
    grep -q '^Verdict: pass$' "factory/reviews/$id.md" || die "factory/reviews/$id.md has no line 'Verdict: pass'"
    if grep -nE '^- \[ \]' "factory/reviews/$id.md" >/dev/null; then die "factory/reviews/$id.md has unchecked items"; fi
  fi
  case "$type" in
    feat|fix)
      git diff --name-only "$MAIN...HEAD" | grep -qx 'CHANGELOG.md' \
        || die "add a line under Unreleased in CHANGELOG.md" ;;
  esac

  # record the proof and regenerate the progress page, as part of the task
  { awk -F'\t' -v id="$id" '$1 != id' "$STATE"
    printf '%s\tdone\t%s\tmake gate green on tree %s\n' "$id" "$(date -u +%Y-%m-%d)" "$(printf '%s' "$tree" | cut -c1-12)"
  } | sort > "$STATE.tmp"
  mv "$STATE.tmp" "$STATE"
  cmd_progress
  git add "$STATE" docs/PROGRESS.md
  git commit -q -m "chore(factory): $id done"

  m="$(mode)"
  if [ "$m" = "pr" ]; then
    git push -q -u origin "$branch"
    gh pr create --base "$MAIN" --head "$branch" --title "$type: $title ($id)" \
      --body "Task $id. Card: factory/tasks. Proof: make gate green on tree $(printf '%s' "$tree" | cut -c1-12)."
    sleep 25
    local tries=0
    until gh pr checks "$branch" --watch --fail-fast; do
      tries=$((tries + 1))
      [ "$tries" -lt 3 ] || die "CI is red or did not report. Fix on $branch, then run gate and finish again"
      sleep 30
    done
    gh pr merge "$branch" --squash --delete-branch
    git checkout -q "$MAIN"
    git pull -q --ff-only origin "$MAIN"
    git branch -D "$branch" >/dev/null 2>&1 || true
  else
    git checkout -q "$MAIN"
    git merge -q --squash "$branch" >/dev/null
    git commit -q -m "$type: $title ($id)"
    git branch -D "$branch" >/dev/null
  fi
  set_local "$id" -
  rm -f "$STAMP"
  echo "FINISHED $id ($m mode). Now on $MAIN at $(git rev-parse --short HEAD)."
  echo "next: $(pick || true)"
}

cmd_block() {
  local id="${1:?usage: block T-NNNN \"reason\"}" reason="${2:?give a one-line reason}"
  local branch; branch="$(branch_of "$id")"
  if [ "$(current_branch)" = "$branch" ]; then
    if ! clean_tree; then git add -A; git commit -q -m "wip: $id blocked"; fi
    git checkout -q "$MAIN"
  fi
  set_local "$id" blocked "$(printf '%s' "$reason" | tr '\t\n' '  ')"
  rm -f "$STAMP"
  echo "BLOCKED $id: $reason"
  echo "next: $(pick || true)"
}

cmd_approve() {
  local id="${1:?usage: approve T-NNNN}"
  [ "$(field "$id" 5)" = "human" ] || die "$id is not a human-gated task"
  set_local "$id" approved "approved $(date -u +%Y-%m-%d)"
  echo "approved $id"
}

cmd_release() {
  local ver="${1:?usage: release X.Y.Z}" id v missing=""
  [ "$(current_branch)" = "$MAIN" ] || die "releases are tagged on $MAIN"
  clean_tree || die "working tree is not clean"
  while IFS="$TAB" read -r id v _; do
    [ "$v" = "$ver" ] || continue
    is_done "$id" || missing="$missing $id"
  done < <(index)
  [ -z "$missing" ] || die "version $ver still has open tasks:$missing"
  index | awk -F'\t' -v v="$ver" '$2 == v { f = 1 } END { exit !f }' || die "no task belongs to version $ver"
  grep -q "^## \[$ver\]" CHANGELOG.md || die "CHANGELOG.md has no section '## [$ver]'"
  grep -qE "^version = \"$ver\"$" Cargo.toml || die "Cargo.toml does not carry version \"$ver\""
  git rev-parse -q --verify "refs/tags/v$ver" >/dev/null && die "tag v$ver already exists"
  git tag -a "v$ver" -m "riehub $ver"
  if [ "$(mode)" = "pr" ]; then git push -q origin "v$ver"; fi
  echo "RELEASED v$ver"
}

case "${1:-}" in
  status)   cmd_status ;;
  next)     cmd_next ;;
  show)     show "${2:?usage: show T-NNNN}" ;;
  start)    cmd_start "${2:-}" ;;
  gate)     cmd_gate ;;
  finish)   cmd_finish "${2:-}" ;;
  block)    cmd_block "${2:-}" "${3:-}" ;;
  approve)  cmd_approve "${2:-}" ;;
  release)  cmd_release "${2:-}" ;;
  progress) cmd_progress ;;
  *) sed -n '2,15p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 1 ;;
esac
